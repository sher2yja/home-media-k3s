def lines(key: str, keys: dict | None = None, password: str | None = None) -> list[str]:
    """Текст инструкции для одного сервиса.

    keys — ключи API Sonarr и Radarr, их читает media.arr_api_key; нужны только
    Jellyseerr. password — пароль торрента из state.json, нужен только ему же.
    Оба необязательны: до установки их ещё нет, и текст обязан собираться и в
    этом случае, иначе окно не откроется на чистой машине.
    """
    keys = keys or {}
    if key == "jellyfin":
        return _jellyfin()
    if key == "prowlarr":
        return _prowlarr()
    if key == "jellyseerr":
        return _jellyseerr(keys)
    if key in ("sonarr", "radarr"):
        return _arr(key)
    if key == "qbittorrent":
        return _qbittorrent(password)
    raise KeyError(f"нет инструкции для {key}")


def _self_check() -> None:
    """Проверяется то, что легко разъезжается: состав и подстановка из config."""
    assert set(ORDER) == {s.key for s in config.SERVICES}, (
        "порядок подвкладок разошёлся с составом сервисов")
    assert set(NEEDS_SETUP) <= set(ORDER)

    for key in ORDER:
        text = "\n".join(lines(key))
        assert text.strip(), f"{key}: пустая инструкция"

    # Пути и порты обязаны приходить из config, а не быть вписанными руками.
    jellyfin = "\n".join(lines("jellyfin"))
    assert config.ROOT_FOLDERS["radarr"] in jellyfin
    assert str(config.BY_KEY["jellyfin"].port) in jellyfin

    seerr = "\n".join(lines("jellyseerr", {"radarr": "КЛЮЧ-Р", "sonarr": "КЛЮЧ-С"}))
    assert "КЛЮЧ-Р" in seerr and "КЛЮЧ-С" in seerr
    assert str(config.BY_KEY["jellyfin"].internal_port) in seerr
    # Без ключей текст обязан собраться — на чистой машине их ещё нет.
    assert "не удалось прочитать" in "\n".join(lines("jellyseerr"))

    torrent = "\n".join(lines("qbittorrent", password="секрет"))
    assert "секрет" in torrent and config.DOWNLOADS_DIR in torrent
    # Логин не вписан словом, а берётся из состояния: человек может задать свой.
    assert config.qbittorrent_login() in torrent
    assert "Пароль:" not in "\n".join(lines("qbittorrent"))

    try:
        lines("нет-такого")
    except KeyError:
        pass
    else:
        raise AssertionError("неизвестный сервис должен приводить к KeyError")

    print("guides.py self-check: OK")


if __name__ == "__main__":
    _self_check()
